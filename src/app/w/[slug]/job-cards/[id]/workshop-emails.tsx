"use client";
import Link from "next/link";
import { useActionState } from "react";
import { Notice } from "@/components/form";
import { btn } from "@/components/ui";
import type { WorkshopEmailRow } from "@/lib/vendorflow/service";
import { workshopEmailStatusAction } from "../actions";
import type { FormState } from "../../actions-util";

function Dismiss({ slug, emailId }: { slug: string; emailId: string }) {
  const [state, action, pending] = useActionState<FormState, FormData>(workshopEmailStatusAction.bind(null, slug, emailId, "dismissed") as (p: FormState, f: FormData) => Promise<FormState>, {});
  return (
    <form action={action} className="inline">
      <button type="submit" disabled={pending} className="rounded-md border border-zinc-300 bg-white px-3 py-1.5 text-sm font-medium disabled:opacity-60">Nothing to enter</button>
      <Notice state={state} />
    </form>
  );
}

/**
 * Replies a workshop sent to the autogenerated email (ADR-033). The workshop never signs in, so what it emailed lands here and its photos and PDFs
 * are among this job card's files. Staff type the figures in with the same form the workshop's link shows.
 */
export function WorkshopEmails({ slug, jobId, emails }: { slug: string; jobId: string; emails: WorkshopEmailRow[] }) {
  const open = emails.filter((e) => e.status === "new");
  if (open.length === 0) return null;
  return (
    <div className="mb-3 space-y-3 rounded-md border border-amber-300 bg-amber-50 p-3 text-sm">
      <p className="font-medium text-amber-900">Received by email, needs entering</p>
      {open.map((e) => (
        <div key={e.id} className="space-y-2 rounded-md border border-amber-200 bg-white p-3">
          <p><span className="text-zinc-500">{e.kind === "quotation" ? "Estimate" : "Invoice"} from </span><span className="font-medium">{e.from_address}</span>
            {!e.sender_matches && <span className="ml-2 rounded bg-amber-100 px-2 py-0.5 text-amber-900">not the address on file for this workshop. Check before you trust it.</span>}</p>
          {e.subject && <p className="text-zinc-700">{e.subject}</p>}
          {e.body_text && <p className="line-clamp-3 whitespace-pre-line text-zinc-600">{e.body_text}</p>}
          <p className="text-zinc-500">{e.file_count === 0 ? "No file saved." : `${e.file_count} file${e.file_count > 1 ? "s" : ""} saved in this job card's files below.`}</p>
          <div className="flex flex-wrap items-center gap-2">
            <Link className={btn} href={`/w/${slug}/job-cards/${jobId}/enter/${e.kind}?email=${e.id}`}>Enter the {e.kind === "quotation" ? "estimate" : "invoice"}</Link>
            <Dismiss slug={slug} emailId={e.id} />
          </div>
        </div>
      ))}
    </div>
  );
}
