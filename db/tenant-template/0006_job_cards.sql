-- Tenant migration 0006: job cards. Idempotent.
-- Moves the rules that must never be bypassed into the database: who may approve, no self-approval, and that every
-- status change leaves an event. The app calls create_job_card / edit_job_card / transition_job_card; the triggers
-- below catch anything that tries to go around them.

create or replace function actor_employee(p_user uuid) returns uuid language sql stable as $$
  select id from employees where user_id = p_user and active
$$;

-- ---------- Guard: transitions, approver, immutability ----------
create or replace function job_card_guard() returns trigger language plpgsql as $$
declare ok boolean; actor text := nullif(current_setting('app.user_id', true), '');
begin
  if tg_op = 'UPDATE' then
    if new.status is distinct from old.status then
      ok := (old.status, new.status) in (
        ('draft','submitted'),('draft','cancelled'),
        ('submitted','approved'),('submitted','rejected'),('submitted','returned_for_edit'),
        ('returned_for_edit','submitted'),('returned_for_edit','cancelled'),
        ('approved','vendor_assigned'),
        ('vendor_assigned','quotation_received'),
        ('quotation_received','quotation_approved'),('quotation_received','vendor_assigned'),
        ('quotation_approved','in_progress'),
        ('in_progress','completed'),
        ('completed','invoiced'),
        ('invoiced','invoice_verified'),('invoiced','completed'),
        ('invoice_verified','closed')
      );
      if not ok then
        raise exception 'illegal job card transition % -> %', old.status, new.status;
      end if;
      if new.status = 'closed' then new.closed_at := now(); end if;

      if new.status = 'approved' then
        if new.approved_by is null then
          raise exception 'approval needs an approver';
        end if;
        if new.approved_by = new.requested_by then
          raise exception 'segregation of duties: the requester cannot approve their own job card';
        end if;
        if actor is null or not exists (select 1 from employees e where e.id = new.approved_by and e.user_id::text = actor) then
          raise exception 'segregation of duties: the approver must be the signed-in user';
        end if;
        if not exists (select 1 from role_permissions rp
                        where rp.role_key = nullif(current_setting('app.role', true), '') and rp.permission_key = 'jobcard.approve') then
          raise exception 'this role may not approve job cards';
        end if;
      end if;
    end if;
    if new.approved_by is distinct from old.approved_by and not (new.status = 'approved' and old.status <> 'approved') then
      raise exception 'the approver can only be set by approving';
    end if;
    if new.requested_by is distinct from old.requested_by and old.status not in ('draft','returned_for_edit') then
      raise exception 'the requester cannot change after submission';
    end if;
  end if;
  new.updated_at := now();
  return new;
end $$;
drop trigger if exists job_cards_guard on job_cards;
create trigger job_cards_guard before update on job_cards
  for each row execute function job_card_guard();

create or replace function job_card_insert_guard() returns trigger language plpgsql as $$
begin
  if new.status <> 'draft' then raise exception 'a job card starts as a draft'; end if;
  if new.approved_by is not null then raise exception 'a new job card has no approver'; end if;
  return new;
end $$;
drop trigger if exists job_cards_insert_guard on job_cards;
create trigger job_cards_insert_guard before insert on job_cards
  for each row execute function job_card_insert_guard();

-- Events written in one transaction share a timestamp, so the timeline is ordered by a sequence instead.
alter table job_card_events add column if not exists seq bigint generated by default as identity;

-- ---------- Every status leaves an event (checked at commit) ----------
create or replace function job_card_event_required() returns trigger language plpgsql as $$
begin
  if not exists (select 1 from job_card_events e
                  where e.job_card_id = new.id and e.to_status = new.status and e.created_at = now()) then
    raise exception 'job card % moved to % without a job_card_events row', new.job_no, new.status;
  end if;
  return null;
end $$;
drop trigger if exists job_cards_event_required_ins on job_cards;
create constraint trigger job_cards_event_required_ins after insert on job_cards
  deferrable initially deferred for each row execute function job_card_event_required();
drop trigger if exists job_cards_event_required_upd on job_cards;
create constraint trigger job_cards_event_required_upd after update of status on job_cards
  deferrable initially deferred for each row when (old.status is distinct from new.status)
  execute function job_card_event_required();

-- The log is append-only. (Cascade deletes from tenant teardown run at trigger depth > 1 and are allowed.)
create or replace function job_card_events_immutable() returns trigger language plpgsql as $$
begin
  if tg_op = 'UPDATE' or pg_trigger_depth() = 1 then
    raise exception 'job_card_events is append-only';
  end if;
  return old;
end $$;
drop trigger if exists job_card_events_no_change on job_card_events;
create trigger job_card_events_no_change before update or delete on job_card_events
  for each row execute function job_card_events_immutable();

-- ---------- Create ----------
create or replace function job_card_save_lines(p_job uuid, p_lines jsonb) returns void language plpgsql as $$
declare l jsonb;
begin
  delete from job_card_lines where job_card_id = p_job;
  for l in select * from jsonb_array_elements(coalesce(p_lines, '[]'::jsonb)) loop
    insert into job_card_lines(job_card_id, kind, description, qty, unit_cost, service_type_key)
    values (p_job, coalesce(nullif(l->>'kind',''), 'service'), l->>'description',
            coalesce(nullif(l->>'qty','')::numeric, 1), coalesce(nullif(l->>'unit_cost','')::numeric, 0),
            nullif(l->>'service_type_key',''));
  end loop;
  update job_cards set estimated_cost = nullif((select sum(qty * unit_cost) from job_card_lines where job_card_id = p_job), 0)
   where id = p_job;
end $$;

-- One call = card + lines + events, all or nothing. requested_by defaults to the caller's own employee record; a
-- manager raising a card for a driver passes the driver's employee id.
create or replace function create_job_card(p jsonb, p_user uuid, p_submit boolean default false) returns uuid
language plpgsql as $$
declare me uuid := actor_employee(p_user); req uuid; new_id uuid; v vehicles;
begin
  req := coalesce(nullif(p->>'requested_by','')::uuid, me);
  if req is null then raise exception 'you need an employee record linked to your login to raise a job card'; end if;
  if not exists (select 1 from employees where id = req and active) then raise exception 'requester is not an active employee'; end if;
  select * into v from vehicles where id = nullif(p->>'vehicle_id','')::uuid;
  if v.id is null then raise exception 'vehicle not found'; end if;
  if v.status = 'disposed' then raise exception 'vehicle is disposed'; end if;

  insert into job_cards(vehicle_id, custodian_id, requested_by, odometer_km, category, reason_code_id, cause_text,
                        description, priority, needed_by)
  values (v.id, custodian_on(v.id, current_date), req, nullif(p->>'odometer_km','')::numeric,
          coalesce(nullif(p->>'category',''), 'corrective'), (p->>'reason_code_id')::uuid, p->>'cause_text',
          nullif(p->>'description',''), coalesce(nullif(p->>'priority',''), 'normal'), nullif(p->>'needed_by','')::date)
  returning id into new_id;
  perform job_card_save_lines(new_id, p->'lines');
  insert into job_card_events(job_card_id, from_status, to_status, actor_id) values (new_id, null, 'draft', p_user);
  if p_submit then perform transition_job_card(new_id, 'submitted', p_user); end if;
  return new_id;
end $$;

-- The requester, or whoever opened the draft, may edit it while it is a draft or sent back.
create or replace function job_card_is_mine(p_job uuid, p_user uuid) returns boolean language sql stable as $$
  select exists (select 1 from job_cards jc where jc.id = p_job and jc.requested_by = actor_employee(p_user))
      or exists (select 1 from job_card_events e where e.job_card_id = p_job and e.from_status is null and e.actor_id = p_user)
$$;

create or replace function edit_job_card(p_job uuid, p jsonb, p_user uuid, p_submit boolean default false) returns void
language plpgsql as $$
declare jc job_cards;
begin
  select * into jc from job_cards where id = p_job for update;
  if jc.id is null then raise exception 'job card not found'; end if;
  if jc.status not in ('draft','returned_for_edit') then raise exception 'only a draft or a returned job card can be edited'; end if;
  if not job_card_is_mine(p_job, p_user) then raise exception 'only the requester can edit this job card'; end if;
  update job_cards set
    vehicle_id = coalesce(nullif(p->>'vehicle_id','')::uuid, vehicle_id),
    custodian_id = custodian_on(coalesce(nullif(p->>'vehicle_id','')::uuid, vehicle_id), current_date),
    odometer_km = nullif(p->>'odometer_km','')::numeric,
    category = coalesce(nullif(p->>'category',''), category),
    reason_code_id = coalesce(nullif(p->>'reason_code_id','')::uuid, reason_code_id),
    cause_text = coalesce(p->>'cause_text', cause_text),
    description = nullif(p->>'description',''),
    priority = coalesce(nullif(p->>'priority',''), priority),
    needed_by = nullif(p->>'needed_by','')::date
   where id = p_job;
  if p ? 'lines' then perform job_card_save_lines(p_job, p->'lines'); end if;
  if p_submit then perform transition_job_card(p_job, 'submitted', p_user); end if;
end $$;

-- ---------- The one way a status changes ----------
-- Who may ask for which target is decided by the app (permission per target); the database enforces the legal
-- transitions, the approver rules and the event row.
create or replace function transition_job_card(p_job uuid, p_to text, p_user uuid, p_comment text default null,
                                               p_patch jsonb default '{}'::jsonb) returns void
language plpgsql as $$
declare jc job_cards; me uuid := actor_employee(p_user); rc uuid; vid uuid;
begin
  select * into jc from job_cards where id = p_job for update;
  if jc.id is null then raise exception 'job card not found'; end if;
  if jc.status = p_to then raise exception 'job card is already %', p_to; end if;
  if p_to in ('rejected','returned_for_edit') and length(trim(coalesce(p_comment, ''))) < 5 then
    raise exception 'a comment of at least 5 characters is required';
  end if;
  if p_to in ('submitted','cancelled') and not job_card_is_mine(p_job, p_user) then
    raise exception 'only the requester can % this job card', case p_to when 'submitted' then 'submit' else 'cancel' end;
  end if;

  if p_to = 'approved' then
    if me is null then raise exception 'you need an employee record linked to your login to approve'; end if;
    rc := nullif(p_patch->>'reason_code_id', '')::uuid;
    if rc is not null and not exists (select 1 from reason_codes where id = rc and active) then raise exception 'reason code not available'; end if;
    update job_cards set status = 'approved', approved_by = me, reason_code_id = coalesce(rc, reason_code_id) where id = p_job;
  elsif p_to = 'vendor_assigned' then
    vid := nullif(p_patch->>'vendor_id', '')::uuid;
    if vid is null or not exists (select 1 from vendors where id = vid and status = 'active') then raise exception 'choose an active vendor'; end if;
    update job_cards set status = 'vendor_assigned', vendor_id = vid where id = p_job;
  else
    update job_cards set status = p_to where id = p_job;
  end if;

  insert into job_card_events(job_card_id, from_status, to_status, actor_id, comment)
  values (p_job, jc.status, p_to, p_user, nullif(trim(coalesce(p_comment, '')), ''));
end $$;

