-- ---------- Attachments ----------
-- A file's storage path must start with this tenant's schema name, and the thing it is attached to must exist here.
create or replace function attachment_guard() returns trigger language plpgsql as $$
begin
  if split_part(new.storage_path, '/', 1) <> current_schema() then
    raise exception 'attachment path must start with the tenant folder';
  end if;
  if new.entity_type = 'job_card' and not exists (select 1 from job_cards where id = new.entity_id) then
    raise exception 'job card not found';
  end if;
  return new;
end $$;
drop trigger if exists attachments_guard on attachments;
create trigger attachments_guard before insert on attachments
  for each row execute function attachment_guard();
